// DOM ELEMENTS
// ============================================================

const menuToggle = document.querySelector(".menu-toggle");
const mainNav = document.querySelector(".main-nav");
const languageButtons = document.querySelectorAll(".language-button");


// ============================================================
// LANGUAGE SWITCHING
// ============================================================

function setLanguage(language) {
    const selectedLanguage =
        translations[language] ? language : "en";

    const dictionary = translations[selectedLanguage];

    // Update document language for accessibility and SEO
    document.documentElement.lang = selectedLanguage;

    // Translate all elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;

        if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
            element.innerHTML = dictionary[key];
        }
    });

    // Update language buttons
    languageButtons.forEach((button) => {
        const active = button.dataset.lang === selectedLanguage;

        button.classList.toggle("active", active);
        button.setAttribute("aria-pressed", String(active));
    });

    // Save selected language
    try {
        localStorage.setItem("bam-language", selectedLanguage);
    } catch (error) {
        // The website still works if localStorage is unavailable.
    }
}


// Register language button events
languageButtons.forEach((button) => {
    button.addEventListener("click", () => {
        setLanguage(button.dataset.lang);
    });
});


// ============================================================
// MOBILE NAVIGATION
// ============================================================

if (menuToggle && mainNav) {

    menuToggle.addEventListener("click", () => {
        const open =
            menuToggle.getAttribute("aria-expanded") !== "true";

        menuToggle.setAttribute("aria-expanded", String(open));

        menuToggle.setAttribute(
            "aria-label",
            open ? "Close navigation" : "Open navigation"
        );

        mainNav.classList.toggle("open", open);
    });


    // Close menu when a navigation link is clicked
    mainNav.querySelectorAll("a").forEach((link) => {
        link.addEventListener("click", () => {
            menuToggle.setAttribute("aria-expanded", "false");
            menuToggle.setAttribute("aria-label", "Open navigation");

            mainNav.classList.remove("open");
        });
    });


    // Close menu with Escape
    document.addEventListener("keydown", (event) => {
        if (event.key === "Escape") {
            menuToggle.setAttribute("aria-expanded", "false");
            menuToggle.setAttribute("aria-label", "Open navigation");

            mainNav.classList.remove("open");
        }
    });
}


// ============================================================
// CONTACT LINKS — WHATSAPP AND EMAIL
// ============================================================

function configureContactLinks() {

    // Validate WhatsApp number: digits only, 8–15 characters
    const whatsappReady =
        /^\d{8,15}$/.test(CONFIG.whatsappNumber);

    // Validate email address
    const emailReady =
        /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(CONFIG.email);


    // Build WhatsApp link
    const whatsappMessage =
        "Hi Emanuel, I'm interested in Buenos Aires Matchday.";

    const whatsappHref = whatsappReady
        ? `https://wa.me/${CONFIG.whatsappNumber}?text=${encodeURIComponent(whatsappMessage)}`
        : "#contact";


    // Build email link
    const emailHref = emailReady
        ? `mailto:${CONFIG.email}?subject=${encodeURIComponent("Buenos Aires Matchday enquiry")}`
        : "#contact";


    // Configure WhatsApp links
    ["whatsapp-link", "floating-whatsapp"].forEach((id) => {

        const link = document.getElementById(id);

        if (!link) return;

        link.href = whatsappHref;

        if (whatsappReady) {
            link.target = "_blank";
            link.rel = "noopener noreferrer";
        } else {
            link.addEventListener("click", (event) => {
                event.preventDefault();

                alert(
                    "Please add Emanuel's WhatsApp number in script.js before publishing the site."
                );
            });
        }
    });


    // Configure email link
    const emailLink = document.getElementById("email-link");

    if (emailLink) {

        emailLink.href = emailHref;

        if (!emailReady) {
            emailLink.addEventListener("click", (event) => {
                event.preventDefault();

                alert(
                    "Please add the contact email in script.js before publishing the site."
                );
            });
        }
    }
}


